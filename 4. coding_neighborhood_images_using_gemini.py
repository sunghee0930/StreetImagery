# 12. SAVE OR UPDATE CHECKPOINT
# ============================================================

def save_checkpoint(
    batch_results
):
    """
    Merge retry results with the existing CSV.

    New rows are placed before old rows. Therefore,
    drop_duplicates(..., keep="first") replaces old FAILED
    rows with the newest retry result.
    """

    new_df = pd.DataFrame(
        batch_results
    ).reindex(
        columns=OUTPUT_COLUMNS
    )

    new_df["folder_id"] = (
        new_df["folder_id"]
        .astype(str)
    )

    new_df["image_id"] = (
        new_df["image_id"]
        .astype(str)
    )

    if os.path.exists(CSV_PATH):

        existing_df = pd.read_csv(
            CSV_PATH,
            on_bad_lines="skip",
            dtype={
                "folder_id": str,
                "image_id": str
            }
        ).reindex(
            columns=OUTPUT_COLUMNS
        )

        existing_df["folder_id"] = (
            existing_df["folder_id"]
            .astype(str)
        )

        existing_df["image_id"] = (
            existing_df["image_id"]
            .astype(str)
        )

        combined_df = pd.concat(
            [
                new_df,
                existing_df
            ],
            ignore_index=True
        )

        combined_df = combined_df.drop_duplicates(
            subset=[
                "folder_id",
                "image_id"
            ],
            keep="first"
        )

    else:
        combined_df = new_df

    combined_df = combined_df.sort_values(
        [
            "folder_id",
            "image_id"
        ]
    ).reset_index(
        drop=True
    )

    temporary_path = (
        CSV_PATH
        + ".tmp"
    )

    combined_df.to_csv(
        temporary_path,
        index=False
    )

    os.replace(
        temporary_path,
        CSV_PATH
    )

    return combined_df


