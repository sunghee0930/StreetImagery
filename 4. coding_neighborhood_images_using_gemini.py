async def analyze_image(
    semaphore,
    folder_id,
    image_id,
    file_path
):
    async with semaphore:

        await asyncio.sleep(
            random.uniform(0.1, 0.3)
        )

        # ----------------------------------------------------
        # Read image from Google Drive with retries and timeout
        # ----------------------------------------------------

        image_bytes = None

        for read_attempt in range(FILE_READ_RETRIES):

            try:
                image_bytes = await asyncio.wait_for(
                    asyncio.to_thread(
                        read_image_bytes,
                        file_path
                    ),
                    timeout=FILE_READ_TIMEOUT_SECONDS
                )

                break

            except asyncio.TimeoutError:
                has_retry_remaining = (
                    read_attempt < FILE_READ_RETRIES - 1
                )

                if has_retry_remaining:
                    wait_time = (
                        (2 ** read_attempt)
                        + random.uniform(0.5, 1.5)
                    )

                    print(
                        f"⚠️ Drive read timeout on {image_id}. "
                        f"Retry {read_attempt + 1}/"
                        f"{FILE_READ_RETRIES} "
                        f"in {wait_time:.1f}s..."
                    )

                    await asyncio.sleep(
                        wait_time
                    )

                    continue

                return empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="FAILED",
                    error=(
                        "TimeoutError: Google Drive file read "
                        f"exceeded {FILE_READ_TIMEOUT_SECONDS} "
                        "seconds after "
                        f"{FILE_READ_RETRIES} attempts."
                    )
                )

            except OSError as error:
                has_retry_remaining = (
                    read_attempt < FILE_READ_RETRIES - 1
                )

                if has_retry_remaining:
                    wait_time = (
                        (2 ** read_attempt)
                        + random.uniform(0.5, 1.5)
                    )

                    print(
                        f"⚠️ Drive read error on {image_id}. "
                        f"Retry {read_attempt + 1}/"
                        f"{FILE_READ_RETRIES} "
                        f"in {wait_time:.1f}s..."
                    )

                    await asyncio.sleep(
                        wait_time
                    )

                    continue

                return empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="FAILED",
                    error=(
                        f"Failed to read file after "
                        f"{FILE_READ_RETRIES} attempts: "
                        f"{type(error).__name__}: {error}"
                    )
                )

            except Exception as error:
                return empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="FAILED",
                    error=(
                        f"Unexpected file-read error: "
                        f"{type(error).__name__}: {error}"
                    )
                )

        if image_bytes is None:
            return empty_result_row(
                folder_id=folder_id,
                image_id=image_id,
                status="FAILED",
                error="Image bytes were not loaded."
            )

        # ----------------------------------------------------
        # Build Gemini image input
        # ----------------------------------------------------

        image_part = types.Part.from_bytes(
            data=image_bytes,
            mime_type="image/jpeg"
        )

        # ----------------------------------------------------
        # Call Gemini with retries and timeout
        # ----------------------------------------------------

        for attempt in range(GEMINI_RETRIES):

            try:
                response = await asyncio.wait_for(
                    aclient.models.generate_content(
                        model=MODEL_NAME,
                        contents=[
                            PROMPT,
                            image_part
                        ],
                        config=types.GenerateContentConfig(
                            response_mime_type=(
                                "application/json"
                            ),
                            response_json_schema=(
                                TriageResult.model_json_schema()
                            )
                        )
                    ),
                    timeout=GEMINI_TIMEOUT_SECONDS
                )

                if not response.text:
                    raise ValueError(
                        "Gemini returned an empty response."
                    )

                parsed = TriageResult.model_validate_json(
                    response.text
                )

                parsed_data = parsed.model_dump()

                result = empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="SUCCESS",
                    error=None
                )

                for (
                    schema_key,
                    csv_header
                ) in SCHEMA_KEY_MAP.items():

                    result[csv_header] = (
                        1
                        if parsed_data.get(schema_key)
                        else 0
                    )

                return result

            except asyncio.TimeoutError:
                has_retry_remaining = (
                    attempt < GEMINI_RETRIES - 1
                )

                if has_retry_remaining:
                    wait_time = (
                        (2 ** attempt)
                        + random.uniform(1, 3)
                    )

                    print(
                        f"⚠️ Gemini timeout on {image_id}. "
                        f"Retry {attempt + 1}/"
                        f"{GEMINI_RETRIES} "
                        f"in {wait_time:.1f}s..."
                    )

                    await asyncio.sleep(
                        wait_time
                    )

                    continue

                full_error = (
                    "TimeoutError: Gemini request exceeded "
                    f"{GEMINI_TIMEOUT_SECONDS} seconds after "
                    f"{GEMINI_RETRIES} attempts."
                )

                print(
                    f"\n❌ Failed image {image_id}:\n"
                    f"{full_error}\n"
                )

                return empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="FAILED",
                    error=full_error
                )

            except Exception as error:
                error_text = str(error).upper()

                transient_markers = [
                    "429",
                    "500",
                    "502",
                    "503",
                    "504",
                    "RESOURCE_EXHAUSTED",
                    "RATE",
                    "QUOTA",
                    "LIMIT",
                    "OVERLOADED",
                    "UNAVAILABLE",
                    "TIMEOUT",
                    "TIMED OUT",
                    "CONNECTION",
                    "CONNECTION RESET",
                    "INTERNAL"
                ]

                is_transient = any(
                    marker in error_text
                    for marker in transient_markers
                )

                has_retry_remaining = (
                    attempt < GEMINI_RETRIES - 1
                )

                if (
                    is_transient
                    and has_retry_remaining
                ):
                    wait_time = (
                        (2 ** attempt)
                        + random.uniform(1, 3)
                    )

                    print(
                        f"⚠️ API error on {image_id}. "
                        f"Retry {attempt + 1}/"
                        f"{GEMINI_RETRIES} "
                        f"in {wait_time:.1f}s..."
                    )

                    await asyncio.sleep(
                        wait_time
                    )

                    continue

                full_error = (
                    f"{type(error).__name__}: "
                    f"{repr(error)}"
                )

                print(
                    f"\n❌ Failed image {image_id}:\n"
                    f"{full_error}\n"
                )

                return empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="FAILED",
                    error=full_error
                )

        return empty_result_row(
            folder_id=folder_id,
            image_id=image_id,
            status="FAILED",
            error="Maximum Gemini retries exceeded."
        )


