def read_image_bytes(
    file_path
):
    """
    Synchronous file-reading helper.

    It is run through asyncio.to_thread(), allowing the main
    asynchronous event loop to remain responsive.
    """

    with open(file_path, "rb") as image_file:
        image_bytes = image_file.read()

    if not image_bytes:
        raise OSError(
            "The image file was read but returned zero bytes."
        )

    return image_bytes


