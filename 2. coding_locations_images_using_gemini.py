async def main():
    processed_images = set()
    if os.path.exists(CSV_PATH):
        try:
            existing_df = pd.read_csv(CSV_PATH)
            if 'status' in existing_df.columns:
                success_df = existing_df[existing_df['status'] == 'SUCCESS']
                processed_images = set(zip(success_df['folder_id'].astype(str), success_df['image_id'].astype(str)))
                print(f"🔄 Checkpoint loaded: {len(processed_images)} images successfully completed.")
            else:
                processed_images = set(zip(existing_df['folder_id'].astype(str), existing_df['image_id'].astype(str)))
        except Exception as e:
            print(f"⚠️ Could not load checkpoint. Error: {e}")

    # Gather target subfolders starting with 260
    subfolders = [d for d in os.listdir(BASE_DIR) if re.match(r"^260\d{4}$", d)]
    print(f"📂 Found {len(subfolders)} subfolders matching the criteria.")

    # Loop and gather all image tasks
    all_image_tasks = []
    for s_folder in subfolders:
        folder_path = os.path.join(BASE_DIR, s_folder)
        images = [img for img in os.listdir(folder_path) if img.lower().endswith(('.jpg', '.jpeg'))]

        for image_file in images:
            image_id = re.sub(r"\D", "", image_file)

            # Skip only if successfully processed
            if (str(s_folder), str(image_id)) in processed_images:
                continue

            file_path = os.path.join(folder_path, image_file)
            all_image_tasks.append((s_folder, image_id, file_path))

    total_tasks = len(all_image_tasks)
    print(f"🚀 Found {total_tasks} remaining images to analyze.")
    if total_tasks == 0:
        print("🎉 All images are already processed successfully!")
        return

    # Concurrency control
    sem = asyncio.Semaphore(40)

    chunk_size = 100
    for i in range(0, total_tasks, chunk_size):
        chunk = all_image_tasks[i:i+chunk_size]
        print(f"⚙️ Processing batch {i // chunk_size + 1} / {-(-total_tasks // chunk_size)}...")

        tasks = [analyze_image(sem, folder, img_id, path) for folder, img_id, path in chunk]
        batch_results = await asyncio.gather(*tasks)

        # Save results iteratively
        new_df = pd.DataFrame(batch_results)
        if os.path.exists(CSV_PATH):
            new_df.to_csv(CSV_PATH, mode='a', header=False, index=False)
        else:
            new_df.to_csv(CSV_PATH, index=False)

        print(f"💾 Checkpoint saved. Progress: {min(i + chunk_size, total_tasks)} / {total_tasks} images analyzed.")

    print(f"\n🎉 SUCCESS! All image pipeline classifications saved to: {CSV_PATH}")

# Launch the processing loop
await main()





