# --- 5. WORKER COROUTINE ---
async def analyze_image(sem, folder_id, image_id, file_path):
    async with sem:
        try:
            with open(file_path, "rb") as f:
                img_bytes = f.read()
        except Exception as e:
            return {"folder_id": folder_id, "image_id": image_id, "error": f"Failed to read file: {e}", "status": "FAILED"}

        image_part = types.Part.from_bytes(data=img_bytes, mime_type="image/jpeg")
        MAX_RETRIES = 5

        for attempt in range(MAX_RETRIES):
            try:
                response = await aclient.models.generate_content(
                    model="gemini-2.5-flash",
                    contents=[PROMPT, image_part],
                    config=types.GenerateContentConfig(
                        response_mime_type="application/json",
                        response_json_schema=TriageResult.model_json_schema(),
                    ),
                )

                parsed = TriageResult.model_validate_json(response.text)
                result_dict = {
                    "folder_id": folder_id,
                    "image_id": image_id,
                    "status": "SUCCESS"
                }

                parsed_data = parsed.model_dump()
                for schema_key, csv_header in SCHEMA_KEY_MAP.items():
                    result_dict[csv_header] = 1 if parsed_data.get(schema_key) else 0

                return result_dict

            except Exception as e:
                err_msg = str(e)
                if "503" in err_msg or "429" in err_msg or "RESOURCE_EXHAUSTED" in err_msg:
                    wait_time = (2 ** attempt) + random.uniform(0, 1)
                    await asyncio.sleep(wait_time)
                else:
                    return {"folder_id": folder_id, "image_id": image_id, "error": f"API Error: {e}", "status": "FAILED"}

        return {"folder_id": folder_id, "image_id": image_id, "error": "Max retries exceeded", "status": "FAILED"}

