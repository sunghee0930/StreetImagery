# 10. WORKER COROUTINE
# ============================================================

async def analyze_image(
    semaphore,
    folder_id,
    image_id,
    file_path
):
    async with semaphore:

        # Small stagger to reduce simultaneous API bursts
        await asyncio.sleep(
            random.uniform(1.0, 2.0)
        )

        try:
            with open(file_path, "rb") as image_file:
                image_bytes = image_file.read()

        except Exception as error:
            return empty_result_row(
                folder_id=folder_id,
                image_id=image_id,
                status="FAILED",
                error=(
                    f"Failed to read file: "
                    f"{type(error).__name__}: {error}"
                )
            )

        image_part = types.Part.from_bytes(
            data=image_bytes,
            mime_type="image/jpeg"
        )

        max_retries = 4

        for attempt in range(max_retries):

            try:
                response = await aclient.models.generate_content(
                    model="gemini-2.5-flash",
                    contents=[
                        PROMPT,
                        image_part
                    ],
                    config=types.GenerateContentConfig(
                        response_mime_type="application/json",
                        response_json_schema=(
                            TriageResult.model_json_schema()
                        )
                    )
                )

                parsed = TriageResult.model_validate_json(
                    response.text
                )

                parsed_data = parsed.model_dump()

                result = empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="SUCCESS",
                    error=None
                )

                for (
                    schema_key,
                    csv_header
                ) in SCHEMA_KEY_MAP.items():

                    result[csv_header] = (
                        1
                        if parsed_data.get(schema_key)
                        else 0
                    )

                return result

            except Exception as error:
                error_text = str(error).upper()

                transient_markers = [
                    "429",
                    "503",
                    "RESOURCE_EXHAUSTED",
                    "RATE",
                    "QUOTA",
                    "LIMIT",
                    "OVERLOADED",
                    "UNAVAILABLE"
                ]

                is_transient = any(
                    marker in error_text
                    for marker in transient_markers
                )

                has_retry_remaining = (
                    attempt < max_retries - 1
                )

                if is_transient and has_retry_remaining:
                    wait_time = (
                        (2 ** attempt)
                        + random.uniform(1, 3)
                    )

                    print(
                        f"⚠️ API limit on {image_id}. "
                        f"Retry {attempt + 1}/{max_retries} "
                        f"in {wait_time:.1f}s..."
                    )

                    await asyncio.sleep(
                        wait_time
                    )

                    continue

                full_error = (
                    f"{type(error).__name__}: {repr(error)}"
                )

                print(
                    f"\n❌ Failed image {image_id}:\n"
                    f"{full_error}\n"
                )

                return empty_result_row(
                    folder_id=folder_id,
                    image_id=image_id,
                    status="FAILED",
                    error=full_error
                )

        return empty_result_row(
            folder_id=folder_id,
            image_id=image_id,
            status="FAILED",
            error="Max retries exceeded"
        )


