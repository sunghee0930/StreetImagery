# 12. MAIN ASYNC COORDINATOR
# ============================================================

async def main():

    processed_images = set()

    # --------------------------------------------------------
    # Load successfully processed images when resuming
    # --------------------------------------------------------

    if (
        os.path.exists(CSV_PATH)
        and not START_FRESH
    ):
        try:
            existing_df = pd.read_csv(
                CSV_PATH,
                on_bad_lines="skip",
                dtype={
                    "folder_id": str,
                    "image_id": str
                }
            )

            if "status" in existing_df.columns:
                success_df = existing_df[
                    existing_df["status"].eq(
                        "SUCCESS"
                    )
                ]

                processed_images = set(
                    zip(
                        success_df["folder_id"],
                        success_df["image_id"]
                    )
                )

                print(
                    f"🔄 Checkpoint loaded: "
                    f"{len(processed_images):,} images "
                    f"successfully completed."
                )

        except Exception as error:
            print(
                "⚠️ Could not load the checkpoint:\n"
                f"{type(error).__name__}: {error}"
            )


    # --------------------------------------------------------
    # Find only the nine PUMA folders
    # --------------------------------------------------------

    subfolders = sorted(
        [
            folder_name
            for folder_name in os.listdir(
                BASE_DIR
            )
            if re.fullmatch(
                r"260\d{4}",
                folder_name
            )
            and os.path.isdir(
                os.path.join(
                    BASE_DIR,
                    folder_name
                )
            )
        ]
    )

    print(
        f"📂 Found {len(subfolders)} "
        f"PUMA subfolders:"
    )

    for folder_name in subfolders:
        print(folder_name)

    if len(subfolders) != 9:
        raise ValueError(
            f"Expected 9 PUMA folders, "
            f"but found {len(subfolders)}:\n"
            f"{subfolders}"
        )


    # --------------------------------------------------------
    # Gather all image tasks
    # --------------------------------------------------------

    all_image_tasks = []

    total_images_found = 0
    skipped_successful = 0

    for folder_id in subfolders:

        folder_path = os.path.join(
            BASE_DIR,
            folder_id
        )

        image_files = sorted(
            [
                filename
                for filename in os.listdir(
                    folder_path
                )
                if filename.lower().endswith(
                    (
                        ".jpg",
                        ".jpeg"
                    )
                )
            ]
        )

        total_images_found += len(
            image_files
        )

        for image_filename in image_files:

            # Preserve the identifier logic from the original pipeline
            image_id = re.sub(
                r"\D",
                "",
                image_filename
            )

            key = (
                str(folder_id),
                str(image_id)
            )

            if (
                not START_FRESH
                and key in processed_images
            ):
                skipped_successful += 1
                continue

            file_path = os.path.join(
                folder_path,
                image_filename
            )

            all_image_tasks.append(
                (
                    folder_id,
                    image_id,
                    file_path
                )
            )


    total_tasks = len(
        all_image_tasks
    )

    print(
        f"\n🖼️ Total images found in shared_radius: "
        f"{total_images_found:,}"
    )

    print(
        f"✅ Previously successful images skipped: "
        f"{skipped_successful:,}"
    )

    print(
        f"🚀 Remaining images to analyze: "
        f"{total_tasks:,}"
    )

    if total_tasks == 0:
        print(
            "🎉 All images are already processed successfully!"
        )

        return


    # --------------------------------------------------------
    # Processing settings
    # --------------------------------------------------------

    semaphore = asyncio.Semaphore(
        30
    )

    chunk_size = 50

    total_batches = (
        total_tasks
        + chunk_size
        - 1
    ) // chunk_size


    # --------------------------------------------------------
    # Process and checkpoint every batch
    # --------------------------------------------------------

    for start_index in range(
        0,
        total_tasks,
        chunk_size
    ):

        batch_number = (
            start_index
            // chunk_size
        ) + 1

        chunk = all_image_tasks[
            start_index:
            start_index + chunk_size
        ]

        print(
            f"\n⚙️ Processing batch "
            f"{batch_number} / "
            f"{total_batches}..."
        )

        tasks = [
            analyze_image(
                semaphore=semaphore,
                folder_id=folder_id,
                image_id=image_id,
                file_path=file_path
            )
            for (
                folder_id,
                image_id,
                file_path
            ) in chunk
        ]

        batch_results = await asyncio.gather(
            *tasks
        )

        combined_df = save_checkpoint(
            batch_results
        )

        batch_df = pd.DataFrame(
            batch_results
        )

        batch_status_counts = (
            batch_df["status"]
            .value_counts(
                dropna=False
            )
        )

        print(
            f"💾 Checkpoint saved. "
            f"Current run progress: "
            f"{min(start_index + chunk_size, total_tasks):,} "
            f"/ {total_tasks:,}"
        )

        print(
            "Batch statuses:"
        )

        print(
            batch_status_counts
        )

        print(
            f"Rows currently stored in run2 CSV: "
            f"{len(combined_df):,}"
        )


    # --------------------------------------------------------
    # Final report
    # --------------------------------------------------------

    final_df = pd.read_csv(
        CSV_PATH,
        on_bad_lines="skip"
    )

    print(
        "\n🎉 Run 2 processing finished."
    )

    print(
        "\nFinal output:"
    )

    print(
        CSV_PATH
    )

    print(
        "\nFinal status counts:"
    )

    print(
        final_df["status"]
        .value_counts(
            dropna=False
        )
    )


# ============================================================
# 13. LAUNCH RUN 2
# ============================================================

await main()



