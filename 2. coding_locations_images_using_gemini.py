# 9. FIXED CSV STRUCTURE
# ============================================================

OUTPUT_COLUMNS = [
    "folder_id",
    "image_id",
    "status",
    *SCHEMA_KEY_MAP.values(),
    "error"
]


def empty_result_row(
    folder_id,
    image_id,
    status,
    error=None
):
    """
    Create a result row with the exact same columns every time.
    This prevents failed rows from corrupting CSV column alignment.
    """

    result = {
        "folder_id": str(folder_id),
        "image_id": str(image_id),
        "status": status
    }

    for csv_header in SCHEMA_KEY_MAP.values():
        result[csv_header] = None

    result["error"] = error

    return result


