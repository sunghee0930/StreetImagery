import requests
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry

MAPILLARY_TOKEN = "MLY|23906238715745799|2d965f9bfc469c30350e928224decb5c"

MAPILLARY_RADIUS_M = 80
MAPILLARY_LIMIT = 50


def make_requests_session():
    s = requests.Session()
    retry = Retry(
        total=5,
        connect=5,
        read=5,
        backoff_factor=0.5,
        status_forcelist=[429, 500, 502, 503, 504],
        allowed_methods=["GET"],
        raise_on_status=False,
    )
    adapter = HTTPAdapter(max_retries=retry, pool_connections=50, pool_maxsize=50)
    s.mount("https://", adapter)
    s.mount("http://", adapter)
    return s


def create_bbox(center_lon, center_lat, radius_meters=80):
    deg_per_meter_lat = 1 / 111000
    deg_per_meter_lon = 1 / (111000 * math.cos(math.radians(center_lat)))

    offset_lat = radius_meters * deg_per_meter_lat
    offset_lon = radius_meters * deg_per_meter_lon

    return (
        center_lon - offset_lon,
        center_lat - offset_lat,
        center_lon + offset_lon,
        center_lat + offset_lat
    )


def check_mapillary_one(row, session):
    point_id = str(row["point_id"])
    qlat = float(row["query_lat"])
    qlon = float(row["query_lon"])

    out = standard_row(point_id, qlat, qlon, "mapillary")

    if MAPILLARY_TOKEN == "PASTE_YOUR_MAPILLARY_TOKEN_HERE":
        out["status"] = "missing_token"
        out["error"] = "Please set MAPILLARY_TOKEN"
        return out

    try:
        west, south, east, north = create_bbox(
            qlon,
            qlat,
            radius_meters=MAPILLARY_RADIUS_M
        )

        bbox_str = f"{west},{south},{east},{north}"

        url = "https://graph.mapillary.com/images"

        params = {
            "access_token": MAPILLARY_TOKEN,
            "bbox": bbox_str,
            "limit": MAPILLARY_LIMIT,
            "fields": "id,captured_at,geometry,compass_angle,camera_type"
        }

        r = session.get(url, params=params, timeout=60)

        if r.status_code != 200:
            out["status"] = "error"
            out["error"] = f"HTTP {r.status_code}: {r.text[:300]}"
            return out

        images = r.json().get("data", [])

        if len(images) == 0:
            out["status"] = "no_image"
            return out

        candidates = []

        for img in images:
            coords = img.get("geometry", {}).get("coordinates", [None, None])
            if coords[0] is None or coords[1] is None:
                continue

            ilon, ilat = coords[0], coords[1]
            d = haversine(qlat, qlon, ilat, ilon)

            if d is None or d > MAPILLARY_RADIUS_M:
                continue

            candidates.append({
                "img": img,
                "source_lat": ilat,
                "source_lon": ilon,
                "dist_m": d
            })

        if len(candidates) == 0:
            out["status"] = "no_image_within_radius"
            return out

        candidates.sort(key=lambda x: x["dist_m"])
        best = candidates[0]
        img = best["img"]

        captured_raw = img.get("captured_at")
        capture_date = None

        if captured_raw is not None:
            ts = pd.to_datetime(captured_raw, unit="ms", errors="coerce", utc=True)
            if not pd.isna(ts):
                capture_date = ts.isoformat()

        out.update({
            "available": True,
            "source_id": str(img.get("id")),
            "capture_date": capture_date,
            "source_lat": best["source_lat"],
            "source_lon": best["source_lon"],
            "dist_m": best["dist_m"],
            "status": "ok",
        })

        return out

    except Exception as e:
        out["status"] = "error"
        out["error"] = f"{type(e).__name__}: {e}"
        return out


