def safe_float(x):
    try:
        if pd.isna(x):
            return None
        return float(x)
    except:
        return None


def haversine(lat1, lon1, lat2, lon2):
    if None in (lat1, lon1, lat2, lon2):
        return None

    R = 6371000.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)

    a = (
        math.sin(dphi / 2) ** 2
        + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
    )

    return 2 * R * math.asin(math.sqrt(a))


def get_obj_latlon(obj):
    lat = getattr(obj, "lat", None)
    lon = getattr(obj, "lon", None)

    if lat is None or lon is None:
        loc = getattr(obj, "location", None)
        if loc is not None:
            lat = getattr(loc, "lat", None)
            lon = getattr(loc, "lon", None)

    return safe_float(lat), safe_float(lon)


async def check_gsv_one(session, row, sem):
    point_id = str(row["point_id"])
    pumaid = row["pumaid"]
    qlat = float(row["query_lat"])
    qlon = float(row["query_lon"])

    out = {
        "point_id": point_id,
        "pumaid": pumaid,
        "query_lat": qlat,
        "query_lon": qlon,
        "source": "google_streetview",
        "available": False,
        "source_id": None,
        "capture_date": None,
        "source_lat": None,
        "source_lon": None,
        "dist_m": None,
        "status": None,
        "error": None,
    }

    async with sem:
        try:
            pano = await streetview.find_panorama_async(
                qlat,
                qlon,
                session,
                radius=RADIUS_M
            )

            if pano is None:
                out["status"] = "no_pano"
                return out

            plat, plon = get_obj_latlon(pano)

            out.update({
                "available": True,
                "source_id": str(getattr(pano, "id", None)),
                "capture_date": str(getattr(pano, "date", None)) if getattr(pano, "date", None) else None,
                "source_lat": plat,
                "source_lon": plon,
                "dist_m": haversine(qlat, qlon, plat, plon),
                "status": "ok",
            })

            return out

        except Exception as e:
            out["status"] = "error"
            out["error"] = f"{type(e).__name__}: {e}"
            return out


async def run_gsv_audit(df):
    timeout = aiohttp.ClientTimeout(total=TIMEOUT)
    sem = asyncio.Semaphore(CONCURRENCY)

