def choose_closest_bing_pano(panos, qlat, qlon):
    if not panos:
        return None, None

    best = None
    best_d = float("inf")

    for p in panos:
        plat, plon = get_obj_latlon(p)
        d = haversine(qlat, qlon, plat, plon)
        if d is not None and d < best_d:
            best = p
            best_d = d

    return best, best_d


