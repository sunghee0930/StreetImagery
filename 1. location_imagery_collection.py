async def check_gsv_one(session, row, sem):
    point_id = str(row["point_id"])
    qlat = float(row["query_lat"])
    qlon = float(row["query_lon"])

    out = standard_row(point_id, qlat, qlon, "google_streetview")

    async with sem:
        try:
            pano = await streetview.find_panorama_async(
                qlat,
                qlon,
                session,
                radius=RADIUS_M
            )

            if pano is None:
                out["status"] = "no_pano"
                return out

            plat, plon = get_obj_latlon(pano)

            out.update({
                "available": True,
                "source_id": str(getattr(pano, "id", None)),
                "capture_date": str(getattr(pano, "date", None)) if getattr(pano, "date", None) else None,
                "source_lat": plat,
                "source_lon": plon,
                "dist_m": haversine(qlat, qlon, plat, plon),
                "status": "ok",
            })

            return out

        except Exception as e:
            out["status"] = "error"
            out["error"] = f"{type(e).__name__}: {e}"
            return out


async def run_gsv_audit(df):
    timeout = aiohttp.ClientTimeout(total=GSV_TIMEOUT)
    sem = asyncio.Semaphore(GSV_CONCURRENCY)

    rows = []
    async with aiohttp.ClientSession(timeout=timeout) as session:
        tasks = [
            check_gsv_one(session, row, sem)
            for _, row in df.iterrows()
        ]

        for coro in tqdm(asyncio.as_completed(tasks), total=len(tasks), desc="Google Street View"):
            rows.append(await coro)

    return pd.DataFrame(rows)


