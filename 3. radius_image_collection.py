# 10. Function to download one GSV panorama
# ============================================================

async def download_one_gsv(session, row, semaphore):
    msgid = str(row["msgid"])
    pumaid = str(row["pumaid"])

    query_lat = float(row["query_lat"])
    query_lon = float(row["query_lon"])

    puma_folder = OUTPUT_DIR / pumaid
    puma_folder.mkdir(parents=True, exist_ok=True)

    image_path = puma_folder / f"{msgid}.jpg"

    result = {
        "msgid": msgid,
        "pumaid": pumaid,
        "query_lon": query_lon,
        "query_lat": query_lat,
        "radius_m": RADIUS_M,
        "zoom": ZOOM,
        "image_path": str(image_path),
        "file_size_bytes": None,
        "download_status": None,
        "download_error": None
    }

    # Skip an image that already exists and appears complete
    if (
        image_path.exists()
        and image_path.stat().st_size >= MINIMUM_FILE_SIZE_BYTES
    ):
        result["file_size_bytes"] = image_path.stat().st_size
        result["download_status"] = "skipped_exists"
        return result

    # Remove a previous empty or suspiciously small file
    if image_path.exists():
        try:
            image_path.unlink()
        except OSError:
            pass

    async with semaphore:
        try:
            panorama = await streetview.find_panorama_async(
                query_lat,
                query_lon,
                session,
                radius=RADIUS_M
            )

            if panorama is None:
                result["download_status"] = "no_panorama"
                return result

            await streetview.download_panorama_async(
                panorama,
                path=str(image_path),
                session=session,
                zoom=ZOOM
            )

            if not image_path.exists():
                raise RuntimeError(
                    "The download function finished, but no image "
                    "file was created."
                )

            file_size = image_path.stat().st_size

            if file_size < MINIMUM_FILE_SIZE_BYTES:
                try:
                    image_path.unlink()
                except OSError:
                    pass

                raise RuntimeError(
                    f"The downloaded file was only {file_size:,} bytes "
                    "and may be incomplete."
                )

            result["file_size_bytes"] = file_size
            result["download_status"] = "ok"

            return result

        except Exception as error:
            result["download_status"] = "error"
            result["download_error"] = (
                f"{type(error).__name__}: {error}"
            )

            # Remove a potentially partial download
            if image_path.exists():
                try:
                    if (
                        image_path.stat().st_size
                        < MINIMUM_FILE_SIZE_BYTES
                    ):
                        image_path.unlink()
                except OSError:
                    pass

            return result


# ============================================================
# 11. Run all downloads with checkpointing
# ============================================================

async def run_downloads_with_checkpoint(data):
    timeout = aiohttp.ClientTimeout(
        total=TIMEOUT_SECONDS
    )

    semaphore = asyncio.Semaphore(
        CONCURRENCY
    )

    current_results = []

    async with aiohttp.ClientSession(
        timeout=timeout
    ) as session:

        tasks = [
            download_one_gsv(
                session=session,
                row=row,
                semaphore=semaphore
            )
            for _, row in data.iterrows()
        ]

        completed_tasks = asyncio.as_completed(tasks)

        for completed_number, task in enumerate(
            tqdm(
                completed_tasks,
                total=len(tasks),
                desc="Downloading GSV panoramas"
            ),
            start=1
        ):
            result = await task
            current_results.append(result)

            if completed_number % CHECKPOINT_EVERY == 0:
                combined_metadata = save_metadata_checkpoint(
                    current_results
                )

                print(
                    f"\nCheckpoint saved after "
                    f"{completed_number:,} locations."
                )

                print(
                    combined_metadata[
                        "download_status"
                    ].value_counts(
                        dropna=False
                    )
                )

    return current_results


