# 9. Helper function for cumulative checkpointing
# ============================================================

def save_metadata_checkpoint(new_rows):
    """
    Combine existing metadata with results from the current run.

    For duplicated msgid values, retain the most recent result.
    """

    new_metadata = pd.DataFrame(new_rows)

    frames = []

    if not existing_metadata.empty:
        frames.append(existing_metadata)

    if not new_metadata.empty:
        frames.append(new_metadata)

    if not frames:
        return pd.DataFrame()

    combined = pd.concat(
        frames,
        ignore_index=True
    )

    combined = combined.drop_duplicates(
        subset=["msgid"],
        keep="last"
    )

    combined = combined.sort_values(
        ["pumaid", "msgid"]
    ).reset_index(drop=True)

    combined.to_csv(
        DOWNLOAD_META_CSV,
        index=False,
        encoding="utf-8-sig"
    )

    return combined


